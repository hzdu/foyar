#!/bin/bash

# ============================================================
# 1. 系统更新（禁用交互式提示）
# ============================================================
export DEBIAN_FRONTEND=noninteractive
apt update
apt upgrade -y -o Dpkg::Options::="--force-confdef" -o Dpkg::Options::="--force-confold"

# ============================================================
# 2. 生成 16 位随机密码（仅大小写字母 + 数字）
# ============================================================
ADMIN_PASS=$(tr -dc A-Za-z0-9 </dev/urandom | head -c 16)

# ============================================================
# 3. 获取服务器公网 IP
# ============================================================
SERVER_IP=$(curl -s -m 5 ifconfig.me || curl -s -m 5 icanhazip.com || echo "你的服务器IP")

# ============================================================
# 4. 保存登录信息到 info.txt
# ============================================================
cat <<EOF > ./info.txt
==================================================
        CyberPanel 自动化安装成功记录
==================================================
后台登录地址: https://${SERVER_IP}:8090
管理员用户名: admin
管理员密  码: ${ADMIN_PASS}
==================================================
提示: 登录后请妥善保管此密码，建议登录面板后自行修改并删除此文件。
EOF

echo -e "\n================================================================="
echo -e "\033[32m [成功] 管理员账号和密码已保存到当前目录的 info.txt \033[0m"
echo -e "=================================================================\n"

# ============================================================
# 5. 下载官方 CyberPanel 安装脚本
# ============================================================
wget -O cyberpanel.sh "https://cyberpanel.sh/?dl"
chmod +x cyberpanel.sh

# ============================================================
# 6. 修改官方脚本，彻底绕过 root 检测
#    将 Check_Root 函数中所有的 "exit 1" 替换为 "return 0"
#    这样即使检测到非 root，也不会退出安装
# ============================================================
sed -i 's/exit 1/return 0/g' cyberpanel.sh

# 额外清除可能残留的 SUDO 环境变量（保险措施）
unset SUDO_USER SUDO_UID SUDO_GID

# ============================================================
# 7. 执行无人值守安装（直接以 root 运行）
# ============================================================
./cyberpanel.sh --version ols --password "${ADMIN_PASS}"